/** Headlines arrive in capitals from the simulation; set them in title case, Spanish style. */
const SMALL = new Set(['a', 'al', 'de', 'del', 'la', 'el', 'los', 'las', 'y', 'e', 'o', 'u', 'en', 'con', 'por', 'para', 'contra', 'sin', 'un', 'una', 'que', 'se', 'le', 'su', 'sus', 'tras']);
export function titleCase(s: string) {
  if (s !== s.toUpperCase()) return s;
  return s.toLowerCase().split(' ').map((word, i) => (i > 0 && SMALL.has(word) ? word : word.replace(/^([¡¿«"(]*)(\p{L})/u, (_, a: string, b: string) => a + b.toUpperCase()))).join(' ');
}
